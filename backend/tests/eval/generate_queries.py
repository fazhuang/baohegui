        """Find case nodes by title ILIKE pattern."""
        return db.query(KGNode).filter(
            KGNode.node_type == 'case',
            KGNode.audit_status == 'verified',
            KGNode.title.ilike(f'%{pattern}%')
        ).limit(max_results).all()

