    # ── Helper: search KG for rule_ids matching keywords ──
    def find_rules(keywords, max_results=5):
        """Find rule_ids that match ANY keyword in title/content/tags."""
        from sqlalchemy import or_
        results = []
        seen = set()
        for kw in keywords:
            matches = db.query(KGNode).filter(
                KGNode.node_type == 'rule',
                KGNode.audit_status == 'verified',
                or_(
                    KGNode.title.ilike(f'%{kw}%'),
                    KGNode.content.ilike(f'%{kw}%'),
                    KGNode.tags.ilike(f'%{kw}%'),
                )
            ).all()
            for m in matches:
                if m.rule_id and m.rule_id not in seen:
                    seen.add(m.rule_id)
                    results.append(m)
                    if len(results) >= max_results:
                        return results
        return results

